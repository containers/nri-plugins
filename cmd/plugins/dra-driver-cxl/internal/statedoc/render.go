// labels are the sections of the header of a record type, in order.
var labels = []string{"Identity", "States", "Transitions", "Invariants", "Persistence", "Locks and waits"}

// header is the doc comment of a record type split into its sections.
type header struct {
	purpose  []string
	sections map[string]string
}

// render returns docs/memory/cxl/states.md for the record types whose Go
// files are in the directories stateDir and containersDir, the release
// policy of the engine whose Go files are in engineDir and the kernel
// objects whose Go files are in the directory kernelDir.
func render(stateDir, containersDir, engineDir, kernelDir string) ([]byte, error) {
	docs, triggers, err := parseState(stateDir)
	if err != nil {
		return nil, err
	}
	ctrDocs, ctrTriggers, err := parseState(containersDir)
	if err != nil {
		return nil, err
	}
	kernelDocs, err := parseKernel(kernelDir)
	if err != nil {
		return nil, err
	}
	var b bytes.Buffer
	b.WriteString("# CXL driver states\n\n")
	b.WriteString("<!-- Generated by go generate in cmd/plugins/dra-driver-cxl from internal/state, internal/engine, internal/containers and pkg/cxl/kernel. Do not edit. -->\n\n")
	b.WriteString("The records that the CXL DRA driver keeps in its store, `state.json` in the plugin data\n")
	b.WriteString("directory of `cxl.nri.io`, and the transitions of every state field. The driver refuses a\n")
	b.WriteString("transition that is not a row of its table. In the effects, \"commit (d)\" is durable before\n")
	b.WriteString("the next externally visible act, \"commit (l)\" is lazy. The part \"Containers\" has the\n")
	b.WriteString("records of the NRI plugin, held in memory; the last part, \"Kernel objects\", has the states\n")
	b.WriteString("of the CXL kernel objects that the driver observes.\n\n")
	b.WriteString("Triggers:\n\n")
	for _, tr := range state.Triggers {
		fmt.Fprintf(&b, "- `%s`: %s\n", tr, escape(triggers[string(tr)]))
	}
	b.WriteString("\n")
	if err := renderObjects(&b, stateObjects(), docs, stateDir, ""); err != nil {
		return nil, err
	}
	b.WriteString("## Invariants over the document\n\n")
	b.WriteString("Checked by `state.Check` over the records alone; the engine checks the invariants that also\n")
	b.WriteString("need the kernel's view.\n\n")
	for _, inv := range state.DocumentInvariants {
		fmt.Fprintf(&b, "- **%s**: %s\n", inv.Name, escape(inv.Text))
	}
	if err := renderEngineInvariants(&b, engineDir); err != nil {
		return nil, err
	}
	if err := renderPolicy(&b, engineDir); err != nil {
		return nil, err
	}
	b.WriteString("\n## Containers\n\n")
	b.WriteString("The records of the NRI plugin of the driver (`internal/containers`), held in memory: Synchronize\n")
	b.WriteString("builds them again after a restart. Triggers:\n\n")
	for _, tr := range containers.Triggers {
		fmt.Fprintf(&b, "- `%s`: %s\n", tr, escape(ctrTriggers[string(tr)]))
	}
	b.WriteString("\n")
	if err := renderObjects(&b, containerObjects(), ctrDocs, containersDir, " (in memory)"); err != nil {
		return nil, err
	}
	if err := renderKernel(&b, kernelDocs, kernelDir); err != nil {
		return nil, err
	}
	return append(bytes.TrimRight(b.Bytes(), "\n"), '\n'), nil
}

// renderObjects writes the sections of the record types of a catalogue:
// the header of each from docs (of the Go files in dir), with suffix after
// its name, and the tables of its states.
func renderObjects(b *bytes.Buffer, objects []object, docs map[string]header, dir, suffix string) error {
	for _, o := range objects {
		h, ok := docs[o.Name]
		if !ok {
			return fmt.Errorf("%s: no doc comment of type %s", dir, o.Name)
		}
		fmt.Fprintf(b, "## %s%s\n\n", o.Name, suffix)
		for _, p := range h.purpose {
			b.WriteString(escape(p) + "\n\n")
		}
		for _, l := range labels {
			fmt.Fprintf(b, "**%s.** %s\n\n", l, escape(capitalize(h.sections[l])))
			if l == "Transitions" {
				for _, t := range o.Tables {
					renderTable(b, t)
				}
			}
		}
	}
	return nil
}

// renderKernel writes the sections of the kernel objects: the header of
// each and the tables of its states.
func renderKernel(b *bytes.Buffer, docs map[string][]kernelParagraph, kernelDir string) error {
	b.WriteString("\n## Kernel objects\n\n")
	b.WriteString("The CXL kernel objects of the node as package `pkg/cxl/kernel` observes them. Their states are the\n")
	b.WriteString("kernel's: they are observed, never applied, and an unchanged state is no transition. The rows are\n")
	b.WriteString("the changes that the operations of the package and the kernel's events make, also those that one\n")
	b.WriteString("operation makes between two observations; the engine logs an observed change that is not a row of\n")
	b.WriteString("its table at debug level (\"kernel transition not in table\").\n\n")
	for _, o := range kernelObjects() {
		h, ok := docs[o.Name]
		if !ok {
			return fmt.Errorf("%s: no header comment of %s", kernelDir, o.Name)
		}
		fmt.Fprintf(b, "## %s (kernel)\n\n", o.Name)
		for _, p := range h {
			if p.label != "" {
				fmt.Fprintf(b, "**%s.** %s\n\n", p.label, escapeText(capitalize(p.text)))
				continue
			}
			b.WriteString(escapeText(p.text) + "\n\n")
		}
		for _, t := range o.Tables {
			renderTable(b, t)
		}
	}
	return nil
}

// renderTable writes a transition table as a markdown table.
func renderTable(b *bytes.Buffer, t fsm.TableText) {
	fmt.Fprintf(b, "### %s.%s\n\n", t.Object, t.Field)
	fmt.Fprintf(b, "States: %s.\n\n", strings.Join(t.States, ", "))
	b.WriteString("| from | to | trigger | guard | effects |\n")
	b.WriteString("|:-----|:---|:--------|:------|:--------|\n")
	for _, r := range t.Rows {
		to := "(unchanged)"
		if !r.Stays {
			to = strings.Join(r.To, ", ")
		}
		trigger := ""
		if len(r.Triggers) > 0 {
			trigger = "`" + strings.Join(r.Triggers, "`, `") + "`"
		}
		switch {
		case trigger != "" && r.When != "":
			trigger += ": " + escape(r.When)
		case r.When != "":
			trigger = escape(r.When)
		}
		fmt.Fprintf(b, "| %s | %s | %s | %s | %s |\n",
			strings.Join(r.From, ", "), to, cell(trigger), cell(escape(r.Guard)), cell(escape(r.Effects)))
	}
	b.WriteString("\n")
	if len(t.Refused) > 0 {
		b.WriteString("Refused:\n\n")
		for _, r := range t.Refused {
			fmt.Fprintf(b, "- %s\n", escape(r))
		}
		b.WriteString("\n")
	}
}

// kernelLabel matches the label of a section of the header comment of a
// kernel object at the start of a line.
var kernelLabel = regexp.MustCompile(`^(Identity|Facts|States|State|Transitions|Invariants|Waits|Hidden kernel state|Kernel rule)( \([A-Za-z]+\))?: `)

// parseKernel returns the header comments of the kernel objects in the Go
// files of the directory dir, by the name that starts each, as paragraphs:
// the purpose and one per labelled section.
func parseKernel(dir string) (map[string][]kernelParagraph, error) {
	names, err := filepath.Glob(filepath.Join(dir, "*.go"))
	if err != nil {
		return nil, err
	}
	sort.Strings(names)
	docs := map[string][]kernelParagraph{}
	fset := token.NewFileSet()
	for _, name := range names {
		if strings.HasSuffix(name, "_test.go") {
			continue
		}
		f, err := parser.ParseFile(fset, name, nil, parser.ParseComments)
		if err != nil {
			return nil, err
		}
		for _, cg := range f.Comments {
			text := cg.Text()
			first, _, _ := strings.Cut(text, "\n")
			object, _, ok := strings.Cut(first, ": ")
			if !ok || !kernelObjectName(object) {
				continue
			}
			if _, dup := docs[object]; dup {
				return nil, fmt.Errorf("%s: a second header comment of %s", name, object)
			}
			docs[object] = kernelParagraphs(text)
		}
	}
	return docs, nil
}

// kernelObjectName tells whether text is the name of a kind of kernel
// object of the catalogue.
func kernelObjectName(text string) bool {
	for _, o := range kernelObjects() {
		if o.Name == text {
			return true
		}
	}
	return false
}

// kernelParagraph is a paragraph of the header comment of a kernel object:
// the purpose (no label) or a labelled section.
type kernelParagraph struct {
	label, text string
}

// kernelParagraphs returns the header comment text as paragraphs: the
// purpose, then a paragraph per labelled section.
func kernelParagraphs(text string) []kernelParagraph {
	var (
		out   []kernelParagraph
		cur   *kernelParagraph
		flush = func() {
			if cur != nil {
				cur.text = strings.TrimSpace(cur.text)
				out = append(out, *cur)
				cur = nil
			}
		}
	)
	for _, line := range strings.Split(text, "\n") {
		line = strings.TrimSpace(line)
		switch {
		case line == "":
			flush()
		case kernelLabel.MatchString(line):
			flush()
			label, rest, _ := strings.Cut(line, ": ")
			cur = &kernelParagraph{label: label, text: rest}
		case cur == nil:
			cur = &kernelParagraph{text: line}
		default:
			cur.text += " " + line
		}
	}
	flush()
	return out
}

// cell returns the text of a table cell: "-" for none.
func cell(text string) string {
	if text == "" {
		return "-"
	}
	return text
}

// escapeText returns the text of a paragraph with the characters that
// markdown would take as markup escaped.
func escapeText(text string) string {
	r := strings.NewReplacer("*", `\*`, "<", "&lt;")
	return r.Replace(text)
}

// escape returns the text of a table cell with the characters that
// markdown would take as markup escaped.
func escape(text string) string {
	r := strings.NewReplacer("|", `\|`, "*", `\*`, "<", "&lt;")
	return r.Replace(text)
}

// parseState returns the headers of the record types and the doc comments
// of the triggers in the Go files of the directory dir.
func parseState(dir string) (map[string]header, map[string]string, error) {
	names, err := filepath.Glob(filepath.Join(dir, "*.go"))
	if err != nil {
		return nil, nil, err
	}
	sort.Strings(names)
	docs := map[string]header{}
	triggers := map[string]string{}
	fset := token.NewFileSet()
	for _, name := range names {
		if strings.HasSuffix(name, "_test.go") {
			continue
		}
		f, err := parser.ParseFile(fset, name, nil, parser.ParseComments)
		if err != nil {
			return nil, nil, err
		}
		for _, d := range f.Decls {
			gd, ok := d.(*ast.GenDecl)
			if !ok {
				continue
			}
			for _, spec := range gd.Specs {
				switch s := spec.(type) {
				case *ast.TypeSpec:
					typeHeader(gd, s, docs)
				case *ast.ValueSpec:
					if err := triggerDoc(s, triggers); err != nil {
						return nil, nil, err
					}
				}
			}
		}
	}
	return docs, triggers, nil
}

// typeHeader adds the header of a record type to docs: a type whose doc
// comment has an Identity section.
func typeHeader(gd *ast.GenDecl, s *ast.TypeSpec, docs map[string]header) {
	doc := s.Doc
	if doc == nil && len(gd.Specs) == 1 {
		doc = gd.Doc
	}
	if doc != nil && strings.Contains(doc.Text(), "\nIdentity: ") {
		docs[s.Name.Name] = splitHeader(doc.Text())
	}
}

// triggerDoc adds the doc comment of a Trigger constant to triggers by its
// value.
func triggerDoc(s *ast.ValueSpec, triggers map[string]string) error {
	if s.Doc == nil || len(s.Values) != 1 {
		return nil
	}
	if id, ok := s.Type.(*ast.Ident); !ok || id.Name != "Trigger" {
		return nil
	}
	lit, ok := s.Values[0].(*ast.BasicLit)
	if !ok {
		return nil
	}
	v, err := strconv.Unquote(lit.Value)
	if err != nil {
		return err
	}
	triggers[v] = strings.TrimPrefix(paragraph(s.Doc.Text()), s.Names[0].Name+" is ")
	return nil
}

// splitHeader returns the doc comment text split into the purpose and the
// labelled sections.
func splitHeader(text string) header {
	h := header{sections: map[string]string{}}
	for _, p := range strings.Split(strings.TrimSpace(text), "\n\n") {
		p = paragraph(p)
		label := ""
		for _, l := range labels {
			if strings.HasPrefix(p, l+": ") {
				label = l
			}
		}
		if label == "" {
			h.purpose = append(h.purpose, p)
			continue
		}
		h.sections[label] = strings.TrimPrefix(p, label+": ")
	}
	return h
}

// capitalize returns text with its first letter in upper case.
func capitalize(text string) string {
	if text == "" {
		return text
	}
	return strings.ToUpper(text[:1]) + text[1:]
}

// paragraph returns the lines of a paragraph joined into one.
func paragraph(text string) string {
	return strings.Join(strings.Fields(text), " ")
}

// renderPolicy writes the release policy of the engine (engine.PolicyRows):
// a row per kind of memdev, a column per release, with the doc comments of
// the constants of the kinds, releases and decisions in engineDir.
func renderPolicy(b *bytes.Buffer, engineDir string) error {
	texts := map[string]map[string]string{}
	for _, typ := range []string{"Kind", "Release", "Decision"} {
		docs, err := constDocs(engineDir, typ)
		if err != nil {
			return err
		}
		texts[typ] = docs
	}
	b.WriteString("## Release policy\n\n")
	b.WriteString("What the release of the last grant of a memdev does with the region of the memdev\n")
	b.WriteString("(`engine.Policy`): a row per kind of memdev, a column per release. A cell with two decisions\n")
	b.WriteString("has the second when regions of other memdevs lie above the region in the decoders of a port.\n\n")
	b.WriteString("| kind |")
	for _, r := range engine.PolicyReleases {
		fmt.Fprintf(b, " %s |", r)
	}
	b.WriteString("\n|:-----|")
	for range engine.PolicyReleases {
		b.WriteString(":---|")
	}
	b.WriteString("\n")
	var kinds []engine.Kind
	for _, row := range engine.PolicyRows {
		kinds = append(kinds, row.Kind)
		fmt.Fprintf(b, "| %s |", row.Kind)
		for _, r := range engine.PolicyReleases {
			d, above := row.Decision(r, false), row.Decision(r, true)
			if d == above {
				fmt.Fprintf(b, " %s |", d)
			} else {
				fmt.Fprintf(b, " %s; %s |", d, above)
			}
		}
		b.WriteString("\n")
	}
	for _, sec := range []struct {
		title, typ string
		values     []string
	}{
		{"Kinds", "Kind", stringsOf(kinds)},
		{"Releases", "Release", stringsOf(engine.PolicyReleases)},
		{"Decisions", "Decision", stringsOf([]engine.Decision{engine.Destroy, engine.InOrder, engine.InOrderIdle, engine.Keep,
			engine.KeepIdle})},
	} {
		fmt.Fprintf(b, "\n%s:\n\n", sec.title)
		for _, v := range sec.values {
			text, ok := texts[sec.typ][v]
			if !ok {
				return fmt.Errorf("%s: no doc comment of the %s %q", engineDir, sec.typ, v)
			}
			fmt.Fprintf(b, "- `%s`: %s\n", v, escape(text))
		}
	}
	return nil
}

// stringsOf returns the values as strings.
func stringsOf[S ~string](values []S) []string {
	out := make([]string, 0, len(values))
	for _, v := range values {
		out = append(out, string(v))
	}
	return out
}

// renderEngineInvariants writes the invariants that the engine checks over
// the records and a kernel observation together: the list invariants in
// the Go files of engineDir.
func renderEngineInvariants(b *bytes.Buffer, engineDir string) error {
	invs, err := invariantDocs(engineDir)
	if err != nil {
		return err
	}
	if len(invs) == 0 {
		return fmt.Errorf("no invariants in %s", engineDir)
	}
	b.WriteString("\n## Invariants over the document and the kernel\n\n")
	b.WriteString("Checked by the engine over the records and its last observation of the kernel; a violation\n")
	b.WriteString("is logged as `engine invariant: <name>: ...`. I11 is the NRI plugin's, of [Container (in memory)](#container-in-memory).\n\n")
	for _, inv := range invs {
		fmt.Fprintf(b, "- **%s**: %s\n", inv[0], escape(inv[1]))
	}
	b.WriteString("\n")
	return nil
}

// invariantDocs returns the names and texts of the elements of the
// variable invariants in the Go files of dir, in their order: composite
// literals with the keys Name and Text, a text a literal or a sum of them.
func invariantDocs(dir string) ([][2]string, error) {
	names, err := filepath.Glob(filepath.Join(dir, "*.go"))
	if err != nil {
		return nil, err
	}
	var out [][2]string
	fset := token.NewFileSet()
	for _, name := range names {
		if strings.HasSuffix(name, "_test.go") {
			continue
		}
		f, err := parser.ParseFile(fset, name, nil, 0)
		if err != nil {
			return nil, err
		}
		for _, d := range f.Decls {
			gd, ok := d.(*ast.GenDecl)
			if !ok || gd.Tok != token.VAR {
				continue
			}
			for _, spec := range gd.Specs {
				s, ok := spec.(*ast.ValueSpec)
				if !ok || len(s.Names) != 1 || s.Names[0].Name != "invariants" || len(s.Values) != 1 {
					continue
				}
				list, ok := s.Values[0].(*ast.CompositeLit)
				if !ok {
					return nil, fmt.Errorf("%s: invariants is not a composite literal", name)
				}
				for _, el := range list.Elts {
					inv, err := invariantDoc(el)
					if err != nil {
						return nil, fmt.Errorf("%s: %w", fset.Position(el.Pos()), err)
					}
					out = append(out, inv)
				}
			}
		}
	}
	return out, nil
}

// invariantDoc returns the Name and the Text of one element of invariants.
func invariantDoc(el ast.Expr) ([2]string, error) {
	var inv [2]string
	lit, ok := el.(*ast.CompositeLit)
	if !ok {
		return inv, fmt.Errorf("an invariant that is not a composite literal")
	}
	for _, e := range lit.Elts {
		kv, ok := e.(*ast.KeyValueExpr)
		if !ok {
			continue
		}
		key, ok := kv.Key.(*ast.Ident)
		if !ok || (key.Name != "Name" && key.Name != "Text") {
			continue
		}
		v, err := stringSum(kv.Value)
		if err != nil {
			return inv, fmt.Errorf("%s: %w", key.Name, err)
		}
		if key.Name == "Name" {
			inv[0] = v
		} else {
			inv[1] = v
		}
	}
	if inv[0] == "" || inv[1] == "" {
		return inv, fmt.Errorf("an invariant without a Name or a Text")
	}
	return inv, nil
}

// stringSum returns the value of a string literal or of a sum of them.
func stringSum(e ast.Expr) (string, error) {
	switch e := e.(type) {
	case *ast.BasicLit:
		if e.Kind != token.STRING {
			return "", fmt.Errorf("not a string literal")
		}
		return strconv.Unquote(e.Value)
	case *ast.BinaryExpr:
		if e.Op != token.ADD {
			return "", fmt.Errorf("not a sum of string literals")
		}
		x, err := stringSum(e.X)
		if err != nil {
			return "", err
		}
		y, err := stringSum(e.Y)
		return x + y, err
	case *ast.ParenExpr:
		return stringSum(e.X)
	}
	return "", fmt.Errorf("not a string literal")
}

// constDocs returns the doc comments of the string constants of the type
// typ in the Go files of dir, by value, without the name of the constant.
func constDocs(dir, typ string) (map[string]string, error) {
	names, err := filepath.Glob(filepath.Join(dir, "*.go"))
	if err != nil {
		return nil, err
	}
	out := map[string]string{}
	fset := token.NewFileSet()
	for _, name := range names {
		if strings.HasSuffix(name, "_test.go") {
			continue
		}
		f, err := parser.ParseFile(fset, name, nil, parser.ParseComments)
		if err != nil {
			return nil, err
		}
		for _, d := range f.Decls {
			gd, ok := d.(*ast.GenDecl)
			if !ok || gd.Tok != token.CONST {
				continue
			}
			for _, spec := range gd.Specs {
				s, ok := spec.(*ast.ValueSpec)
				if !ok || s.Doc == nil || len(s.Values) != 1 {
					continue
				}
				if id, ok := s.Type.(*ast.Ident); !ok || id.Name != typ {
					continue
				}
				lit, ok := s.Values[0].(*ast.BasicLit)
				if !ok {
					continue
				}
				v, err := strconv.Unquote(lit.Value)
				if err != nil {
					return nil, err
				}
				text := paragraph(s.Doc.Text())
				if t, ok := strings.CutPrefix(text, s.Names[0].Name+" is "); ok {
					text = t
				} else {
					text = strings.TrimPrefix(text, s.Names[0].Name+" ")
				}
				out[v] = capitalize(text)
			}
		}
	}
	return out, nil
}
